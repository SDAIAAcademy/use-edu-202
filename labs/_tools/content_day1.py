ATTENDANCE = [("الصحة", 120, 96), ("الأعمال", 200, 130), ("القانون", 80, 60), ("الهندسة", 150, 105), ("التعليم", 100, 59)]


def pct(a: int, b: int) -> float:
    return round(a / b * 100, 1)


def attendance_table(education_present: int | None = None) -> str:
    L = ["حضور المحاضرات المسائية في الأسبوع السابع، جامعة الدهناء (بيانات اصطناعية)", "", "الكلية | المسجلون | الحاضرون | النسبة"]
    for name, enrolled, present in ATTENDANCE:
        if name == "التعليم" and education_present is not None:
            present = education_present
        L.append(f"{name} | {enrolled} | {present} | {round(present / enrolled * 100)}%")
    return "\n".join(L) + "\n"


def attendance_facts() -> dict:
    rates = {n: pct(p, e) for n, e, p in ATTENDANCE}
    enrolled = sum(e for _, e, _ in ATTENDANCE)
    present = sum(p for _, _, p in ATTENDANCE)
    return {
        "mean_of_rates": round(sum(rates.values()) / len(rates), 1),
        "overall_rate": pct(present, enrolled),
        "enrolled": enrolled,
        "present": present,
        "highest": max(rates, key=rates.get),
        "lowest": min(rates, key=rates.get),
        "lowest_after_change": min({**rates, "التعليم": pct(95, 100)}, key={**rates, "التعليم": pct(95, 100)}.get),
    }


